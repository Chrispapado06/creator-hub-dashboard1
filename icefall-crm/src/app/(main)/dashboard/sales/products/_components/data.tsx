/**
 * Placeholder rows for the Products screens.
 *
 * The shapes mirror the CRM's real tables one for one, so wiring the data
 * layer later is a swap of these arrays for reads — not a rewrite of the
 * screens. Two schema facts the screens depend on and must keep stating:
 *   · a product carries NO destination link, which is why Mountain reads "—"
 *     and the mountain filter has nothing to fill it with;
 *   · a commission rate is copied onto the commission row at conversion, so
 *     commission is summed from stored rows and never recomputed at read time.
 *
 * Every company and product name here is invented.
 */

export type ProductStatus = "draft" | "pending_review" | "live" | "archived";
export type PriceState = "known" | "on_request" | "unknown";
export type VerificationStatus = "unverified" | "pending" | "verified" | "rejected" | "suspended";
export type PlacementStatus = "reserved" | "active" | "expired" | "cancelled";

export type Company = {
  id: string;
  name: string;
  verification_status: VerificationStatus;
};

export type Product = {
  id: string;
  company_id: string;
  kind: "expedition" | "trek";
  slug: string;
  name: string;
  /** NULL whenever price_state is not "known". */
  price_from_cents: number | null;
  price_state: PriceState;
  duration_days_min: number | null;
  duration_days_max: number | null;
  season: string | null;
  difficulty: string | null;
  max_altitude_m: number | null;
  status: ProductStatus;
  live_at: string | null;
};

export type Commission = {
  id: string;
  /** Copied at conversion. Never looked up again at read time. */
  rate_bps: number | null;
  amount_cents: number;
};

export type BookingDetailed = {
  id: string;
  product_id: string | null;
  /** NULL is a real state — a booking whose value nobody has recorded yet. */
  value_cents: number | null;
  booked_at: string;
  commissions: Commission[];
};

export type Enquiry = {
  id: string;
  product_id: string | null;
  created_at: string;
  /** Lifecycle is timestamps, never a status column. */
  answered_at: string | null;
};

export type PlacementRow = {
  id: string;
  /** NULL means the slot is bought and nothing has been put in it yet. */
  product_id: string | null;
  destination_id: string;
  slot_position: number;
  status: PlacementStatus;
  price_cents: number | null;
  starts_on: string;
  ends_on: string;
};

