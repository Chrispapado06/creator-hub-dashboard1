/**
 * Opening a support ticket from the phone app.
 *
 * WHAT THIS REPLACED, AND WHY IT HAD TO GO
 *
 * Settings → Help offered three rows, and all three called `window.open` on a
 * `mailto:` — `support@icefall.app` twice and `safety@icefall.app` once. There
 * is no mailbox behind either address. The screen's own disclaimer admitted it
 * ("There is no support desk behind the addresses yet"), which made it honest
 * and useless at the same time: a climber with a real problem composed a mail
 * in their own mail app, sent it, and it went nowhere at all. The failure was
 * invisible to them and invisible to ICEFALL — nobody could even count how many
 * people had tried.
 *
 * THE ONE CALL, AND THE ARGUMENT IT IS NOT ALLOWED TO WIN
 *
 * `open_support_ticket` derives WHO the requester is from `auth.uid()` — company
 * first, then guide, then staff, then athlete — and stamps it on the row. There
 * is deliberately no argument for it. This module must never grow one: a form
 * that asked "what kind of user are you?" is a form somebody can answer
 * wrongly, and the desk would then sort a climber's booking problem into the
 * operator queue on the strength of a mis-tap.
 *
 * WHAT COMES BACK IS PROOF, AND IT IS THE POINT
 *
 * The reference (`ICE-000107`) is generated by a trigger on insert. Showing it
 * is the only way a person can tell that their message was STORED rather than
 * merely accepted by a screen. Nothing in this app may look sent that was not
 * stored — so there is no optimistic success state here, and no local queue
 * that would let the UI say "sent" while the row does not exist.
 *
 * NO SILENT QUEUE, DELIBERATELY. The obvious kindness — keep it on the device
 * and retry later — is the exact thing the honesty doctrine forbids here,
 * because the person walks away believing they have been heard. If it cannot be
 * sent, this module says so and the screen keeps what they typed so they can
 * send it themselves when there is signal.
 */

