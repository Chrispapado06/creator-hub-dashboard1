export type SupportFailure =
  | "no-backend"
  | "signed-out"
  | "offline"
  | "too-short"
  | "refused";

export type SupportResult =
  | { ok: true; reference: string; id: string; kind: string }
  | { ok: false; reason: SupportFailure; message: string };

/**
 * Postgres speaks to operators, not to climbers.
 *
 * `permission denied for function open_support_ticket` is accurate and unusable.
 * Anything not explicitly recognised here becomes one plain sentence rather
 * than a raw `error.message`, and the caller keeps what the person typed.
 */
function readFailure(code: string | undefined, message: string): {
  reason: SupportFailure;
  message: string;
} {
  const m = message.toLowerCase();

  // The grant, and the in-function guard, are the same situation to a person.
  if (code === "42501" || m.includes("not signed in") || m.includes("permission denied")) {
    return { reason: "signed-out", message: SUPPORT_SIGNED_OUT };
  }
  // The database's own validation sentences are written for a human. Keep them.
  if (m.includes("a little more detail")) {
    return { reason: "too-short", message: "Please describe the problem in a little more detail." };
  }
  if (m.includes("needs a subject")) {
    return { reason: "refused", message: "A support request needs a subject." };
  }
  // fetch failures surface as a TypeError with no code, and mean the same thing
  // to somebody in a hut as `navigator.onLine === false` does.
  if (code === undefined && (m.includes("fetch") || m.includes("network"))) {
    return { reason: "offline", message: SUPPORT_NOT_SENT };
  }
  return {
    reason: "refused",
    message:
      "ICEFALL could not open this request, and it has not been stored. What you wrote is still here — trying again is worth a go.",
  };
}

export async function openSupportTicket(input: {
  subject: string;
  body: string;
  type: SupportType;
  /**
   * Where they were when they asked.
   *
   * TRIAGE METADATA, NEVER AUTHORITY TO ACT. A desk that reads "they were on
   * /settings/membership" as "they want their membership changed" has turned a
   * breadcrumb into an instruction. It records the screen; it never records a
   * request.
   */
  originScreen: string;
}): Promise<SupportResult> {
  if (!supabase) {
    return { ok: false, reason: "no-backend", message: SUPPORT_NO_BACKEND };
  }

  const subject = input.subject.trim();
  const body = input.body.trim();

  if (body.length < MIN_BODY_CHARS) {
    return {
      ok: false,
      reason: "too-short",
      message: `Please describe the problem in a little more detail — at least ${MIN_BODY_CHARS} characters.`,
    };
  }

  // Checked BEFORE the call so an offline attempt says "offline" rather than
  // whatever a dropped fetch happens to look like.
  if (typeof navigator !== "undefined" && navigator.onLine === false) {
    return { ok: false, reason: "offline", message: SUPPORT_NOT_SENT };
  }

  // Signed out is not an error to recover from; it is a different screen. Asked
  // here so the person is told the true reason rather than a permissions string.
  const { data: sess } = await supabase.auth.getSession();
  if (!sess.session) {
    return { ok: false, reason: "signed-out", message: SUPPORT_SIGNED_OUT };
  }

  try {
    const { data, error } = await supabase.rpc("open_support_ticket", {
      p_subject: subject.slice(0, MAX_SUBJECT_CHARS),
      p_body: body,
      p_type: input.type,
      p_origin_app: "phone_app",
      p_origin_screen: input.originScreen.slice(0, 200),
    });

    if (error) {
      const f = readFailure(error.code, error.message ?? "");
      return { ok: false, ...f };
    }

    // Belt and braces: a shape we do not recognise is NOT a success. Saying
    // "sent" on a response we cannot read the reference out of would be exactly
    // the lie this module exists to prevent.
    const row = data as { ok?: boolean; id?: string; reference?: string; kind?: string } | null;
    if (!row?.ok || !row.reference || !row.id) {
      return {
        ok: false,
        reason: "refused",
        message:
          "ICEFALL could not confirm this was stored, so it is not being reported as sent. What you wrote is still here.",
      };
    }

    return { ok: true, reference: row.reference, id: row.id, kind: row.kind ?? "athlete" };
  } catch (e) {
    const f = readFailure(undefined, e instanceof Error ? e.message : String(e));
    return { ok: false, ...f };
  }
}
